-- Lapisan per KHG (scripts/impor_khg.sh): kolom sumber pada layer yang belum punya, tabel baru untuk
-- jalur pompa, badan air, sub-KHG (unit prioritas) dan DMPG, atribut tambahan pompa & logger TMA.
-- Jalankan sekali di DB lama, lalu jalankan ulang 10_api_views.sql:
--   psql -v ON_ERROR_STOP=1 -f db/migrations/2026-10-27_lapisan_khg.sql -f db/10_api_views.sql
BEGIN;

ALTER TABLE peta.sungai         ADD COLUMN IF NOT EXISTS sumber text;
ALTER TABLE peta.pompa          ADD COLUMN IF NOT EXISTS sumber text;
ALTER TABLE peta.pompa          ADD COLUMN IF NOT EXISTS atribut jsonb;
ALTER TABLE peta.logger_tmat    ADD COLUMN IF NOT EXISTS nama text;
ALTER TABLE peta.logger_tmat    ADD COLUMN IF NOT EXISTS sumber text;
ALTER TABLE peta.logger_tmat    ADD COLUMN IF NOT EXISTS atribut jsonb;
ALTER TABLE peta.hotspot        ADD COLUMN IF NOT EXISTS sumber text;
ALTER TABLE peta.areal_terbakar ADD COLUMN IF NOT EXISTS sumber text;

CREATE TABLE IF NOT EXISTS peta.jalur_pompa (     -- rute pompa -> lahan sasaran lewat kanal
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode          text,                               -- route_id sumber
  panjang_m     numeric(10,1),
  angkat_m      numeric(6,2),                       -- lift
  debit_m3s     numeric(8,3),
  layanan_ha    numeric(10,1),
  sumber        text,
  atribut       jsonb,
  khg_id        int REFERENCES ref.khg,
  geom          geometry(MultiLineString,4326) NOT NULL
);

CREATE TABLE IF NOT EXISTS peta.badan_air (       -- sungai/danau berupa poligon
  id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama   text,
  sumber text,
  khg_id int REFERENCES ref.khg,
  geom   geometry(MultiPolygon,4326) NOT NULL
);

CREATE TABLE IF NOT EXISTS analisis.unit_prioritas (   -- sub-KHG + skor prioritas
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  unit_id        text NOT NULL,                        -- "KHG_KAHSEB_S01"
  kelas          text,
  peringkat      smallint,
  skor_dampak    numeric(6,4),
  skor_kelayakan numeric(6,4),
  skor_urgensi   numeric(6,4),
  skor_risiko    numeric(6,4),
  pengelola      text,
  luas_ha        numeric(12,1),
  sumber         text,
  atribut        jsonb,                                -- seluruh kolom indikator sumber
  khg_id         int REFERENCES ref.khg,
  geom           geometry(MultiPolygon,4326) NOT NULL
);

CREATE TABLE IF NOT EXISTS analisis.dmpg (    -- program Desa Mandiri Peduli Gambut / pembagian intervensi
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program text NOT NULL,                       -- "Intervensi KLH/BPLH", "Intervensi Perusahaan", ...
  luas_ha numeric(12,1),
  sumber  text,
  khg_id  int REFERENCES ref.khg,
  geom    geometry(MultiPolygon,4326) NOT NULL
);

CREATE INDEX IF NOT EXISTS jalur_pompa_geom ON peta.jalur_pompa USING gist (geom);
CREATE INDEX IF NOT EXISTS jalur_pompa_khg ON peta.jalur_pompa (khg_id);
CREATE INDEX IF NOT EXISTS badan_air_geom ON peta.badan_air USING gist (geom);
CREATE INDEX IF NOT EXISTS badan_air_khg ON peta.badan_air (khg_id);
CREATE INDEX IF NOT EXISTS unit_prioritas_geom ON analisis.unit_prioritas USING gist (geom);
CREATE INDEX IF NOT EXISTS unit_prioritas_khg ON analisis.unit_prioritas (khg_id);
CREATE INDEX IF NOT EXISTS dmpg_geom ON analisis.dmpg USING gist (geom);
CREATE INDEX IF NOT EXISTS dmpg_khg ON analisis.dmpg (khg_id);

GRANT SELECT ON peta.jalur_pompa, peta.badan_air, analisis.unit_prioritas, analisis.dmpg TO gambut_baca;

COMMIT;
